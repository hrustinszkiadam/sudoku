/**
 * Offline puzzle generator. Writes INSERT statements to seeds/puzzles.sql.
 *
 *   pnpm gen:puzzles -- --per-difficulty 500 --seed 42
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { parseArgs } from "node:util";
import { DIFFICULTIES } from "../src/shared/constants";
import {
	countSolutions,
	type GeneratedPuzzle,
	generate,
	mulberry32,
} from "../src/shared/sudoku";

const { values } = parseArgs({
	args: process.argv.slice(2).filter((a) => a !== "--"),
	options: {
		"per-difficulty": { type: "string", default: "500" },
		seed: { type: "string", default: "42" },
		out: { type: "string", default: "seeds/puzzles.sql" },
	},
});

const perDifficulty = Number(values["per-difficulty"]);
const seed = Number(values.seed);
if (!Number.isInteger(perDifficulty) || perDifficulty < 1) {
	throw new Error("--per-difficulty must be a positive integer");
}
if (!Number.isInteger(seed)) throw new Error("--seed must be an integer");

const BATCH = 100;
const createdAt = Date.UTC(2026, 0, 1);
const lines: string[] = [
	`-- Generated by scripts/generate-puzzles.ts --per-difficulty ${perDifficulty} --seed ${seed}`,
];

for (const [d, difficulty] of DIFFICULTIES.entries()) {
	// Independent stream per difficulty so changing one count keeps the others stable.
	const rng = mulberry32(seed * 31 + d);
	const rows: string[] = [];
	const started = performance.now();
	for (let n = 0; n < perDifficulty; n++) {
		const p: GeneratedPuzzle = generate(rng, difficulty);
		if (countSolutions(p.givens) !== 1) {
			throw new Error(`Generated a non-unique puzzle: ${p.givens}`);
		}
		const id = `${difficulty}-${seed}-${String(n).padStart(5, "0")}`;
		rows.push(
			`('${id}','${p.givens}','${p.solution}','${difficulty}',${p.score},${createdAt})`,
		);
		if ((n + 1) % 50 === 0) {
			process.stderr.write(`\r${difficulty}: ${n + 1}/${perDifficulty}`);
		}
	}
	const secs = ((performance.now() - started) / 1000).toFixed(1);
	process.stderr.write(`\r${difficulty}: ${perDifficulty} in ${secs}s\n`);
	for (let i = 0; i < rows.length; i += BATCH) {
		lines.push(
			"INSERT OR IGNORE INTO puzzles (id, givens, solution, difficulty, score, created_at) VALUES",
			`${rows.slice(i, i + BATCH).join(",\n")};`,
		);
	}
}

mkdirSync(dirname(values.out), { recursive: true });
writeFileSync(values.out, `${lines.join("\n")}\n`);
process.stderr.write(`Wrote ${values.out}\n`);
